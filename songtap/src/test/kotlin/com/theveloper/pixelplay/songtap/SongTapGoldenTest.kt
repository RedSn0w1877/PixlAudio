package com.theveloper.pixelplay.songtap

import java.io.File
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * The golden vectors that are checked in must be exactly what the code generates today. When this fails
 * after an intended change to the pure logic: bump `GoldenGenerator.SPEC_VERSION`, run
 * `./gradlew :songtap:generateGolden`, commit the files, and copy them to the iOS fixtures. Never edit a
 * golden file by hand.
 */
class SongTapGoldenTest {

    private val dir = File(GoldenGenerator.GOLDEN_DIR)
    private val generated by lazy { GoldenGenerator.generate() }

    @Test
    fun `regeneration equals the checked-in files`() {
        assertTrue(dir.isDirectory, "missing ${dir.absolutePath}: run ./gradlew :songtap:generateGolden")
        val onDisk = dir.listFiles().orEmpty().filter { it.isFile }.map { it.name }.sorted()
        assertEquals(generated.keys.sorted(), onDisk, "the set of golden files")
        for ((name, content) in generated) {
            val expected = content.toByteArray(Charsets.UTF_8)
            val actual = File(dir, name).readBytes()
            if (!expected.contentEquals(actual)) {
                val a = String(actual, Charsets.UTF_8).split('\n')
                val e = content.split('\n')
                var line = 0
                while (line < a.size && line < e.size && a[line] == e[line]) line++
                val was = if (line < a.size) a[line].take(300) else "<end of file>"
                val now = if (line < e.size) e[line].take(300) else "<end of file>"
                throw AssertionError("$name differs at line ${line + 1}\n checked in: $was\n generated:  $now")
            }
        }
    }

    @Test
    fun `the manifest lists every file with its hash`() {
        val manifest = File(dir, GoldenGenerator.MANIFEST).readLines().filter { it.isNotEmpty() }
        val listed = manifest.associate { it.substring(66) to it.substring(0, 64) }
        val files = dir.listFiles().orEmpty().filter {
            it.isFile && it.name != GoldenGenerator.MANIFEST && it.name != GoldenGenerator.SPEC_VERSION_FILE
        }
        assertEquals(files.map { it.name }.sorted(), listed.keys.sorted())
        for (file in files) assertEquals(listed[file.name], GoldenGenerator.sha256(file.readBytes()), file.name)
    }

    @Test
    fun `the spec version file is the code's version`() {
        assertEquals(GoldenGenerator.SPEC_VERSION.toString(), File(dir, GoldenGenerator.SPEC_VERSION_FILE).readText().trim())
    }

    @Test
    fun `the files have the sizes the spec asks for`() {
        fun count(file: String, fn: String): Int = generated[file]!!.split('\n').count { it.startsWith("{\"fn\":\"$fn\",") }
        assertTrue(count("payload.jsonl", "encode") >= 50)
        assertTrue(count("payload.jsonl", "decode") >= 800)
        assertTrue(count("session.jsonl", "trace") >= 180)
        assertTrue(count("detector.jsonl", "detector") >= 70)
        assertEquals(2 * 2 * 34, count("timeline.jsonl", "frame"))
    }

    @Test
    fun `generation is deterministic`() {
        val again = GoldenGenerator.generate()
        assertEquals(generated.keys.toList(), again.keys.toList())
        for ((name, content) in generated) assertEquals(content, again[name], name)
    }
}
